function wordmark(text, gap = 2) {
	const rows = Array(16).fill("");
	[...text].forEach((ch, i) => {
		const g = GLYPHS[ch];
		for (let y = 0; y < 16; y++) rows[y] += (i > 0 ? ".".repeat(gap) : "") + g[y];
	});
	return rows;
}

const WORD = wordmark("NO FUN OS");
const FACE_GAP = 4;

export const LOGO_WIDTH = WORD[0].length;
export const WORD_HEIGHT = WORD.length;

// Composite bitmap: '#' = wordmark (burns), '@' = face (no flames), '.' = empty.
export const LOGO_ROWS = (() => {
	const pad = (LOGO_WIDTH - FACE[0].length) >> 1;
	const face = FACE.map((r) =>
		(".".repeat(pad) + r.replaceAll("#", "@")).padEnd(LOGO_WIDTH, "."),
	);
	return [...WORD, ...Array(FACE_GAP).fill(".".repeat(LOGO_WIDTH)), ...face];
})();

export const LOGO_HEIGHT = LOGO_ROWS.length;

export function createLogoTexture() {
	const data = new Uint8Array(LOGO_WIDTH * LOGO_HEIGHT * 2);
	LOGO_ROWS.forEach((row, y) => {
		const ty = LOGO_HEIGHT - 1 - y;
		for (let x = 0; x < LOGO_WIDTH; x++) {
			const i = (ty * LOGO_WIDTH + x) * 2;
			data[i] = row[x] === "#" ? 255 : 0;
			data[i + 1] = row[x] === "@" ? 255 : 0;
		}
	});

	const texture = new THREE.DataTexture(
		data,
		LOGO_WIDTH,
		LOGO_HEIGHT,
		THREE.RGFormat,
		THREE.UnsignedByteType,
	);
	texture.unpackAlignment = 1;
	texture.magFilter = THREE.NearestFilter;
	texture.minFilter = THREE.NearestFilter;
	texture.generateMipmaps = false;
	texture.needsUpdate = true;
	return texture;
}
